function syncDaysFromDates() {
    const s = $('tripDateStart'), e = $('tripDateEnd');
    if (s.value && e.value) {
        const diff = Math.ceil((new Date(e.value) - new Date(s.value)) / (1000 * 60 * 60 * 24)) + 1;
        if (diff > 0 && diff <= 90) { state.days = diff; updateDaysButtons(diff); calculate(); }
    }
}

